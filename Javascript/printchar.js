const tech="react";

// to print the total length of the character
console.log(tech.length);

// to print the first character
console.log(tech[0]); // works only in javascript
console.log(tech.charAt(0)); // works in both javascript and java

// to print the second character
console.log(tech[1]);
console.log(tech.charAt(1));

// to print the last character
console.log(tech[tech.length-1]);
console.log(tech.charAt(tech.length-1));